import { spawnSync } from 'node:child_process'
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

/**
 * The Client artifact must be a classic script that registers a lazy factory
 * with the platform module loader. This mirrors the wrapper DSH's own packages
 * ship (see @deepseek-ai/dsh-client-ui-sidebar-documentpreview/lib/client.js):
 * a CommonJS bundle whose `module.exports` is the plugin object.
 *
 * esbuild is driven through its CLI (not the JS API) because the file sandbox
 * cannot hand a child process piped stdio; the CLI spawns its binary with
 * `stdio: 'inherit'`, which is allowed.
 */
const root = fileURLToPath(new URL('.', import.meta.url))
const pkg = JSON.parse(await readFile(new URL('./package.json', import.meta.url), 'utf8'))
const ID = pkg.name
const OUT_DIR = fileURLToPath(new URL('.build/', import.meta.url))
const INTERMEDIATE = `${OUT_DIR}client.cjs`
const ARTIFACT = fileURLToPath(new URL('client.js', import.meta.url))

await mkdir(OUT_DIR, { recursive: true })

const esbuildBin = fileURLToPath(new URL('node_modules/esbuild/bin/esbuild', import.meta.url))
const build = spawnSync(process.execPath, [
  esbuildBin,
  fileURLToPath(new URL('src/client/index.tsx', import.meta.url)),
  '--bundle',
  '--format=cjs',
  '--platform=browser',
  '--target=es2022',
  '--jsx=automatic',
  '--define:process.env.NODE_ENV="production"',
  '--external:react',
  '--external:react/jsx-runtime',
  '--external:react-dom',
  '--external:react-dom/client',
  `--outfile=${INTERMEDIATE}`,
  '--log-level=warning',
], { stdio: 'inherit', cwd: root })

if (build.status !== 0) {
  console.error(`esbuild failed with status ${build.status}`)
  process.exit(build.status ?? 1)
}

const code = (await readFile(INTERMEDIATE, 'utf8')).trim()
const artifact = [
  '// Generated by build.mjs — do not edit by hand.',
  `window.__ModuleLoader__.load({id:\`${ID}\`,factory:require=>{var module={exports:{}};var exports=module.exports;`,
  'Object.defineProperty(exports,Symbol.toStringTag,{value:`Module`});',
  code,
  ';return module.exports}})',
  '',
].join('\n')

// Atomic swap: the HMR pump stat()s this file, and a poll landing mid-write
// would publish a truncated bundle.
const temp = `${ARTIFACT}.tmp`
await writeFile(temp, artifact, 'utf8')
await rename(temp, ARTIFACT)
console.log(`client.js written (${(artifact.length / 1024).toFixed(1)} KiB)`)

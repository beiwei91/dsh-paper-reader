import { spawnSync } from 'node:child_process'
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

/**
 * Builds both Client artifacts as classic scripts that register a lazy factory
 * with the platform module loader:
 *
 *   client.js          the always-loaded half (tab registration, empty state)
 *   client.pdf.js      the lazily loaded chunk (PDF.js + the reader), fetched by
 *                      `require.async('./client.pdf.js')`
 *
 * The CommonJS-in-a-factory wrapper mirrors DSH's own packages (see
 * @deepseek-ai/dsh-client-ui-sidebar-documentpreview/lib/client.js).
 *
 * esbuild is driven through its CLI (not the JS API) because the file sandbox
 * cannot hand a child process piped stdio; the CLI spawns its binary with
 * `stdio: 'inherit'`, which is allowed.
 */
const root = fileURLToPath(new URL('.', import.meta.url))
const pkg = JSON.parse(await readFile(new URL('./package.json', import.meta.url), 'utf8'))
const ID = pkg.name
const OUT_DIR = fileURLToPath(new URL('.build/', import.meta.url))
const CHUNK_FILE = 'client.pdf.js'
const WORKER_PACKAGE_FILE = fileURLToPath(new URL('node_modules/pdfjs-dist/build/pdf.worker.min.mjs', import.meta.url))
const WORKER_TEXT = `${OUT_DIR}pdf-worker.txt`

await mkdir(OUT_DIR, { recursive: true })
await writeFile(WORKER_TEXT, await readFile(WORKER_PACKAGE_FILE, 'utf8'), 'utf8')

const esbuildBin = fileURLToPath(new URL('node_modules/esbuild/bin/esbuild', import.meta.url))

function runEsbuild(args) {
  const result = spawnSync(process.execPath, [esbuildBin, ...args], { stdio: 'inherit', cwd: root })
  if (result.status !== 0) {
    console.error(`esbuild failed with status ${result.status}`)
    process.exit(result.status ?? 1)
  }
}

/**
 * Wrap one CommonJS module in the loader registration the platform expects.
 * @param code bundle text
 * @param chunk when set, the chunk file name this artifact registers as
 */
function wrap(code, chunk) {
  return [
    '// Generated by build.mjs — do not edit by hand.',
    `window.__ModuleLoader__.load({id:\`${ID}\`${chunk === undefined ? '' : `,chunk:\`${chunk}\``},factory:require=>{`,
    'var module={exports:{}};var exports=module.exports;',
    'Object.defineProperty(exports,Symbol.toStringTag,{value:`Module`});',
    'var __dshRequireAsync=require.async.bind(require);',
    code,
    ';return module.exports}})',
    '',
  ].join('\n')
}

async function writeAtomic(file, content) {
  const target = fileURLToPath(new URL(file, import.meta.url))
  const temp = `${target}.tmp`
  await writeFile(temp, content, 'utf8')
  // The HMR pump stat()s the artifact; a poll landing mid-write would publish a
  // truncated bundle.
  await rename(temp, target)
  console.log(`${file} written (${(content.length / 1024).toFixed(1)} KiB)`)
}

// 1. The reader chunk: PDF.js plus the viewer, minified for the wire.
const CHUNK_OUT = `${OUT_DIR}client.pdf.cjs`
runEsbuild([
  fileURLToPath(new URL('src/client/pdf/chunk.tsx', import.meta.url)),
  '--bundle',
  '--format=cjs',
  '--platform=browser',
  '--target=es2022',
  '--jsx=automatic',
  '--loader:.txt=text',
  '--minify',
  '--define:process.env.NODE_ENV="production"',
  '--external:react',
  '--external:react/jsx-runtime',
  `--outfile=${CHUNK_OUT}`,
  '--log-level=warning',
])
await writeAtomic(CHUNK_FILE, wrap((await readFile(CHUNK_OUT, 'utf8')).trim(), CHUNK_FILE))

// 3. The Host half: routes plus the read-only agent tools. PDF.js is bundled in
// so the profile needs no runtime dependency for text extraction.
const HOST_OUT = fileURLToPath(new URL('lib/host.js', import.meta.url))
await mkdir(fileURLToPath(new URL('lib/', import.meta.url)), { recursive: true })
runEsbuild([
  fileURLToPath(new URL('src/host/index.ts', import.meta.url)),
  '--bundle',
  '--format=esm',
  '--platform=node',
  '--target=node20',
  '--external:canvas',
  '--external:@napi-rs/canvas',
  `--outfile=${HOST_OUT}`,
  '--log-level=warning',
])
console.log(`lib/host.js written (${((await readFile(HOST_OUT)).length / 1024).toFixed(1)} KiB)`)

// 2. The always-loaded half.
const MAIN_OUT = `${OUT_DIR}client.cjs`
runEsbuild([
  fileURLToPath(new URL('src/client/index.tsx', import.meta.url)),
  '--bundle',
  '--format=cjs',
  '--platform=browser',
  '--target=es2022',
  '--jsx=automatic',
  '--define:process.env.NODE_ENV="production"',
  '--external:react',
  '--external:react/jsx-runtime',
  '--external:react-dom',
  '--external:react-dom/client',
  `--outfile=${MAIN_OUT}`,
  '--log-level=warning',
])
await writeAtomic('client.js', wrap((await readFile(MAIN_OUT, 'utf8')).trim()))
